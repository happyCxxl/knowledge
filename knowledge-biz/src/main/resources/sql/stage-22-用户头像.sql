USE knowledge;

-- 只存对象 key（如 avatar/1723958123456789/a3f9c2d1.png），不存 URL：
-- 绝对地址与部署拓扑耦合，换主机/端口就会全部失效。
-- 每次上传换一个新 key，所以路径不可变、可长缓存，不需要额外的版本参数。
ALTER TABLE kb_user
    ADD COLUMN avatar VARCHAR(255) DEFAULT NULL COMMENT '头像对象 key：avatar/{userId}/{随机段}.{扩展名}' AFTER phone;
